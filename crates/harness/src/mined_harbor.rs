    #[test]
    fn golden_fixture_matches_byte_for_byte() {
        let task = fixture_task();
        let files = render_task_files(&task, &fixture_dir(), SpecLevel::S2, &golden_prov())
            .expect("render");
        let golden = golden_dir();
        if std::env::var("MINED_HARBOR_BLESS").as_deref() == Ok("1") {
            let _ = std::fs::remove_dir_all(&golden);
            for (rel, bytes) in &files {
                let path = golden.join(rel);
                std::fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
                std::fs::write(&path, bytes).expect("write");
            }
            panic!("blessed; re-run without MINED_HARBOR_BLESS");
        }
        let mut want: Vec<PathBuf> = files.iter().map(|(p, _)| p.clone()).collect();
        want.sort();
        assert_eq!(rel_files(&golden), want, "golden path set differs");
        for (rel, bytes) in &files {
            let got = std::fs::read(golden.join(rel)).expect("golden file");
            assert!(&got == bytes, "golden mismatch at {}", rel.display());
        }
    }
