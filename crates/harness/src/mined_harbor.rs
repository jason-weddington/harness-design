/// Run a git command, returning trimmed stdout or an error carrying stderr.
fn git_ok(args: &[&std::ffi::OsStr], what: &str) -> Result<String, String> {
    let out = git_command()
        .args(args)
        .output()
        .map_err(|e| format!("{what}: spawn git: {e}"))?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
    } else {
        Err(format!(
            "{what}: git failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        ))
    }
}

/// `HEAD` of the repo containing `path`, plus `-dirty` when the tree has changes; `unknown` on any failure.
fn git_sha_of(path: &Path) -> String {
    let p = path.as_os_str();
    let Ok(head) = git_ok(
        &["-C".as_ref(), p, "rev-parse".as_ref(), "HEAD".as_ref()],
        "",
    ) else {
        return "unknown".to_string();
    };
    match git_ok(
        &["-C".as_ref(), p, "status".as_ref(), "--porcelain".as_ref()],
        "",
    ) {
        Ok(status) if status.is_empty() => head,
        Ok(_) => format!("{head}-dirty"),
        Err(_) => "unknown".to_string(),
    }
}

/// Refuse an output dir inside any git work tree (bundles of private repos must never be committed).
fn guard_out_dir(out: &Path) -> Result<(), String> {
    let probe = out
        .ancestors()
        .find(|p| p.exists())
        .ok_or_else(|| format!("--out `{}` has no existing ancestor", out.display()))?;
    let res = git_command()
        .arg("-C")
        .arg(probe)
        .args(["rev-parse", "--is-inside-work-tree"])
        .output()
        .map_err(|e| format!("--out guard: spawn git: {e}"))?;
    if res.status.success() && String::from_utf8_lossy(&res.stdout).trim() == "true" {
        return Err(format!(
            "--out `{}` is inside a git work tree; emitted tasks contain bundles of private repos and must never be committed",
            out.display()
        ));
    }
    Ok(())
}

/// `git -C <repo> merge-base --is-ancestor <a> <b>`: `Ok(true)` on exit 0, `Ok(false)` on exit 1.
fn is_ancestor(repo: &Path, a: &str, b: &str, task_id: &str) -> Result<bool, String> {
    let out = git_command()
        .arg("-C")
        .arg(repo)
        .args(["merge-base", "--is-ancestor", a, b])
        .output()
        .map_err(|e| format!("task `{task_id}`: spawn git merge-base: {e}"))?;
    match out.status.code() {
        Some(0) => Ok(true),
        Some(1) => Ok(false),
        _ => Err(format!(
            "task `{task_id}`: git merge-base --is-ancestor {a} {b} failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        )),
    }
}

/// Build a bundle at `dest` carrying only `talos-baseline` at `sha` from `src`; with `fix_sha`, audit the ancestry first.
fn create_bundle(
    src: &Path,
    sha: &str,
    dest: &Path,
    fix_sha: Option<&str>,
    task_id: &str,
) -> Result<(), String> {
    let what = format!("task `{task_id}`: bundle of {}", src.display());
    let tmp = tempfile::TempDir::new().map_err(|e| format!("{what}: tempdir: {e}"))?;
    let bare = tmp.path().join("src.git");
    git_ok(
        &[
            "clone".as_ref(),
            "--bare".as_ref(),
            "--quiet".as_ref(),
            src.as_os_str(),
            bare.as_os_str(),
        ],
        &what,
    )?;
    if let Some(fix) = fix_sha {
        if is_ancestor(&bare, fix, sha, task_id)? {
            return Err(format!(
                "task `{task_id}`: fix_sha is an ancestor of parent_sha (contaminated)"
            ));
        }
        if !is_ancestor(&bare, sha, fix, task_id)? {
            return Err(format!(
                "task `{task_id}`: parent_sha is not an ancestor of fix_sha"
            ));
        }
    }
    let b = bare.as_os_str();
    git_ok(
        &[
            "-C".as_ref(),
            b,
            "update-ref".as_ref(),
            BASELINE_REF.as_ref(),
            sha.as_ref(),
        ],
        &what,
    )?;
    git_ok(
        &[
            "-C".as_ref(),
            b,
            "bundle".as_ref(),
            "create".as_ref(),
            dest.as_os_str(),
            BASELINE_REF.as_ref(),
        ],
        &what,
    )?;
    let heads = bundle_heads(dest, &what)?;
    let expected = format!("{sha} {BASELINE_REF}");
    if heads != expected {
        return Err(format!(
            "{what}: bundle heads `{heads}`, expected exactly `{expected}`"
        ));
    }
    Ok(())
}

/// `git bundle list-heads <bundle>`, trimmed.
fn bundle_heads(bundle: &Path, what: &str) -> Result<String, String> {
    git_ok(
        &["bundle".as_ref(), "list-heads".as_ref(), bundle.as_os_str()],
        what,
    )
}

/// Source repo path of the primary and of each sibling (siblings sit next to the primary, as [`crate::mined_task::SiblingRepo`] documents).
fn source_repos(task: &MinedTask) -> Result<(PathBuf, Vec<PathBuf>), String> {
    let primary = PathBuf::from(expand_home(&task.repo_path));
    let parent = primary
        .parent()
        .ok_or_else(|| format!("task `{}`: repo_path has no parent", task.id))?
        .to_path_buf();
    let siblings = task
        .env
        .sibling_repos
        .iter()
        .map(|s| parent.join(&s.repo))
        .collect();
    Ok((primary, siblings))
}

/// Resolve each sibling's pin to a full commit sha on the host.
fn resolve_sibling_shas(task: &MinedTask) -> Result<Vec<(String, String)>, String> {
    let (_, sources) = source_repos(task)?;
    task.env
        .sibling_repos
        .iter()
        .zip(sources)
        .map(|(sibling, src)| {
            let spec = format!("{}^{{commit}}", sibling.pin);
            let sha = git_ok(
                &[
                    "-C".as_ref(),
                    src.as_os_str(),
                    "rev-parse".as_ref(),
                    "--verify".as_ref(),
                    spec.as_ref(),
                ],
                &format!("task `{}`: resolve sibling `{}`", task.id, sibling.repo),
            )?;
            Ok((sibling.repo.clone(), sha))
        })
        .collect()
}

// ===== vendored uv git dependencies ========================================
//
// A task's `uv.lock` may pin a git dependency fetched over ssh. The image build has no ssh client and no keys (and must not get them), so the emitter clones each such dependency on the host, ships its pinned ancestry as `environment/gitdeps/<name>.bundle`, and redirects the url to a local bare repo with `url.<file>.insteadOf` inside the image. https git sources and registry deps are left alone.
//
// `uv.lock` is read with a narrowly-scoped line scanner rather than a TOML parser: the `toml` crate is not a workspace dependency, and the only shape needed is uv's `source = { git = "<url>" }` inline table, whose url never contains a quote or escape.

/// The ref every git-dependency bundle carries at the pinned commit (so the commit is reachable after a bare clone).
const GITDEP_REF: &str = "refs/heads/talos-gitdep";

/// One ssh-sourced git dependency pinned by a `uv.lock`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GitDep {
    /// The url with its `?query` and `#fragment` stripped: what git is asked to fetch.
    pub fetch_url: String,
    /// The pinned 40-hex commit from the url's `#fragment`.
    pub commit: String,
}

impl GitDep {
    /// Filesystem-safe name: a slug of the url path's last segment plus the first 12 hex of the commit.
    #[must_use]
    pub fn name(&self) -> String {
        let path = self
            .fetch_url
            .split_once("://")
            .map_or(self.fetch_url.as_str(), |(_, rest)| rest);
        let path = path.rsplit_once(':').map_or(path, |(_, p)| p);
        let last = path.trim_end_matches('/').rsplit('/').next().unwrap_or("");
        let last = last.strip_suffix(".git").unwrap_or(last);
        let slug: String = last
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-') {
                    c
                } else {
                    '-'
                }
            })
            .collect();
        let slug = slug.trim_start_matches(|c: char| !c.is_ascii_alphanumeric());
        let slug = if slug.is_empty() { "dep" } else { slug };
        format!("{slug}-{}", &self.commit[..12])
    }
}

/// `ssh://…` or scp-style `user@host:path` (no scheme).
fn is_ssh_git_url(url: &str) -> bool {
    if url.starts_with("ssh://") {
        return true;
    }
    if url.contains("://") {
        return false;
    }
    match (url.find('@'), url.find(':')) {
        (Some(at), Some(colon)) => at > 0 && colon > at + 1,
        _ => false,
    }
}

/// Every ssh-sourced `source = { git = "<url>" }` in `lock`, deduplicated by `(fetch_url, commit)`, in first-seen order.
///
/// # Errors
/// An ssh git source with no 40-hex `#<sha>` fragment (fail closed; never guess a ref), or an unterminated url string. Every message names `task_id` and the url.
pub fn parse_uv_lock_git_deps(lock: &str, task_id: &str) -> Result<Vec<GitDep>, String> {
    const NEEDLE: &str = "source = { git = \"";
    let mut deps: Vec<GitDep> = Vec::new();
    for line in lock.lines() {
        let mut rest = line;
        while let Some(start) = rest.find(NEEDLE) {
            let after = &rest[start + NEEDLE.len()..];
            let end = after.find('"').ok_or_else(|| {
                format!("task `{task_id}`: uv.lock: unterminated git source in `{line}`")
            })?;
            let url = &after[..end];
            rest = &after[end + 1..];
            if !is_ssh_git_url(url) {
                continue;
            }
            let (base, fragment) = url.split_once('#').unwrap_or((url, ""));
            if !is_full_sha(fragment) {
                return Err(format!(
                    "task `{task_id}`: uv.lock git source `{url}` has no 40-hex `#<sha>` commit"
                ));
            }
            let fetch_url = base.split_once('?').map_or(base, |(u, _)| u).to_string();
            let dep = GitDep {
                fetch_url,
                commit: fragment.to_string(),
            };
            if !deps.contains(&dep) {
                deps.push(dep);
            }
        }
    }
    Ok(deps)
}

/// `uv.lock` of `repo` at `sha`, or `None` when that commit has no top-level `uv.lock`.
fn uv_lock_at(repo: &Path, sha: &str, what: &str) -> Result<Option<String>, String> {
    let r = repo.as_os_str();
    let listed = git_ok(
        &[
            "-C".as_ref(),
            r,
            "ls-tree".as_ref(),
            "--name-only".as_ref(),
            sha.as_ref(),
            "uv.lock".as_ref(),
        ],
        what,
    )?;
    if listed.is_empty() {
        return Ok(None);
    }
    let spec = format!("{sha}:uv.lock");
    let out = git_command()
        .arg("-C")
        .arg(repo)
        .args(["show", &spec])
        .output()
        .map_err(|e| format!("{what}: spawn git: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "{what}: git failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        ));
    }
    Ok(Some(String::from_utf8_lossy(&out.stdout).into_owned()))
}

/// The ssh git dependencies of the primary's `uv.lock` at `parent_sha` and of each sibling's at its pin, deduplicated.
///
/// # Errors
/// A git failure reading a lockfile, any [`parse_uv_lock_git_deps`] error, or one fetch url pinned at two different commits (a single `insteadOf` cannot serve both).
fn discover_git_deps(
    task: &MinedTask,
    sibling_shas: &[(String, String)],
) -> Result<Vec<GitDep>, String> {
    let (primary, sibling_sources) = source_repos(task)?;
    let mut repos: Vec<(&Path, &str)> = vec![(&primary, &task.parent_sha)];
    for ((_, sha), src) in sibling_shas.iter().zip(&sibling_sources) {
        repos.push((src, sha));
    }
    let mut deps: Vec<GitDep> = Vec::new();
    for (repo, sha) in repos {
        let what = format!("task `{}`: read uv.lock of {}", task.id, repo.display());
        let Some(lock) = uv_lock_at(repo, sha, &what)? else {
            continue;
        };
        for dep in parse_uv_lock_git_deps(&lock, &task.id)? {
            if let Some(other) = deps
                .iter()
                .find(|d| d.fetch_url == dep.fetch_url && d.commit != dep.commit)
            {
                return Err(format!(
                    "task `{}`: git dependency `{}` is pinned at both {} and {}",
                    task.id, dep.fetch_url, other.commit, dep.commit
                ));
            }
            if !deps.contains(&dep) {
                deps.push(dep);
            }
        }
    }
    Ok(deps)
}

/// Clone `dep` on the host and write the pinned commit's ancestry to `dest`, carrying [`GITDEP_REF`] at the commit.
///
/// `git_env` is added to every git subprocess (tests use it to redirect the url to a local repo).
fn bundle_git_dep(
    dep: &GitDep,
    dest: &Path,
    git_env: &[(String, String)],
    task_id: &str,
) -> Result<(), String> {
    let what = format!("task `{task_id}`: git dependency {}", dep.fetch_url);
    let tmp = tempfile::TempDir::new().map_err(|e| format!("{what}: tempdir: {e}"))?;
    let bare = tmp.path().join("dep.git");
    let run = |args: &[&std::ffi::OsStr]| -> Result<(), String> {
        let out = git_command()
            .envs(git_env.iter().map(|(k, v)| (k, v)))
            .args(args)
            .output()
            .map_err(|e| format!("{what}: spawn git: {e}"))?;
        if out.status.success() {
            Ok(())
        } else {
            Err(format!(
                "{what}: git failed: {}",
                String::from_utf8_lossy(&out.stderr).trim()
            ))
        }
    };
    run(&[
        "clone".as_ref(),
        "--bare".as_ref(),
        "--quiet".as_ref(),
        dep.fetch_url.as_ref(),
        bare.as_os_str(),
    ])?;
    let b = bare.as_os_str();
    let spec = format!("{}^{{commit}}", dep.commit);
    run(&[
        "-C".as_ref(),
        b,
        "cat-file".as_ref(),
        "-e".as_ref(),
        spec.as_ref(),
    ])
    .map_err(|e| format!("{e} (pinned commit {} not found)", dep.commit))?;
    run(&[
        "-C".as_ref(),
        b,
        "update-ref".as_ref(),
        GITDEP_REF.as_ref(),
        dep.commit.as_ref(),
    ])?;
    run(&[
        "-C".as_ref(),
        b,
        "bundle".as_ref(),
        "create".as_ref(),
        dest.as_os_str(),
        GITDEP_REF.as_ref(),
    ])
}

/// The Dockerfile lines that unpack `dep`'s bundle into a local bare repo and redirect its url there.
fn gitdep_lines(task_id: &str, dep: &GitDep) -> String {
    let name = dep.name();
    let git = format!("/opt/talos-task/gitdeps/{name}.git");
    format!(
        "COPY gitdeps/{name}.bundle /opt/talos-task/gitdeps/\n\
         RUN git clone --quiet --bare /opt/talos-task/gitdeps/{name}.bundle {git} && git -C {git} cat-file -e {commit}^{{commit}} || {{ echo \"TALOS_EVAL_INVALID reason=gitdep-missing-commit task={task_id}\"; exit 1; }}\n\
         RUN git config --system url.\"file://{git}\".insteadOf \"{url}\"\n",
        commit = dep.commit,
        url = dep.fetch_url,
    )
}

