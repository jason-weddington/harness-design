/// The per-task line the example prints.
#[must_use]
pub fn format_emitted_line(
    id: &str,
    level: SpecLevel,
    sibling_shas: &[(String, String)],
    path: &Path,
) -> String {
    let siblings = if sibling_shas.is_empty() {
        "-".to_string()
    } else {
        sibling_shas
            .iter()
            .map(|(r, s)| format!("{r}@{s}"))
            .collect::<Vec<_>>()
            .join(",")
    };
    format!(
        "emitted task={id} level={} gate=armed siblings={siblings} -> {}",
        level.slug(),
        path.display()
    )
}

/// The per-task line for an emitted dir, with sibling shas read back from its bundles.
///
/// # Errors
/// The source task.json or a sibling bundle cannot be read.
pub fn emitted_line(args: &EmitArgs, id: &str, path: &Path) -> Result<String, String> {
    let task = load_task(&args.tasks_dir.join(id)).map_err(|e| e.to_string())?;
    let mut shas = Vec::with_capacity(task.env.sibling_repos.len());
    for sibling in &task.env.sibling_repos {
        let bundle = path
            .join("environment/siblings")
            .join(format!("{}.bundle", sibling.repo));
        let heads = bundle_heads(&bundle, &format!("task `{id}`"))?;
        let sha = heads
            .split_whitespace()
            .next()
            .unwrap_or_default()
            .to_string();
        shas.push((sibling.repo.clone(), sha));
    }
    Ok(format_emitted_line(id, args.spec_level, &shas, path))
}

/// The `tier2:` hint for an emitted dir: the `scripts/tier2-harbor.sh` invocation for `out`.
#[must_use]
pub fn run_hint(out: &Path) -> String {
    format!(
        "tier2: scripts/tier2-harbor.sh --tasks {} --jobs <jobs>",
        out.display()
    )
}

