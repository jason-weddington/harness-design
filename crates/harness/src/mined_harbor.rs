/// Emit one task dir as `<out>/<id>`, atomically (built in `<out>/.<id>.partial`, renamed at the end).
///
/// # Errors
/// Any [`render_task_files`] error (in which case nothing is created under `out`), `<out>/<id>` already existing, a sibling provenance that does not match the task, an unreadable or unpinned `uv.lock` git dependency, or any bundle / IO failure (in which case the partial dir is removed).
pub fn emit_task(
    task_dir: &Path,
    out: &Path,
    level: SpecLevel,
    prov: &EmitProvenance,
) -> Result<PathBuf, String> {
    emit_task_with_git_env(task_dir, out, level, prov, &[])
}

/// [`emit_task`] with `git_env` added to the git subprocesses that fetch vendored git dependencies.
fn emit_task_with_git_env(
    task_dir: &Path,
    out: &Path,
    level: SpecLevel,
    prov: &EmitProvenance,
    git_env: &[(String, String)],
) -> Result<PathBuf, String> {
    let task = load_task(task_dir).map_err(|e| e.to_string())?;
    let mut files = render_task_files(&task, task_dir, level, prov)?;
    let names: Vec<&str> = task
        .env
        .sibling_repos
        .iter()
        .map(|s| s.repo.as_str())
        .collect();
    let prov_names: Vec<&str> = prov.sibling_shas.iter().map(|(r, _)| r.as_str()).collect();
    if names != prov_names || !prov.sibling_shas.iter().all(|(_, s)| is_full_sha(s)) {
        return Err(format!(
            "task `{}`: sibling_shas {:?} do not match the task's siblings {names:?}",
            task.id, prov.sibling_shas
        ));
    }
    let out = absolutize_cwd(out)?;
    let dest = out.join(&task.id);
    if dest.exists() {
        return Err(format!(
            "task `{}`: {} already exists",
            task.id,
            dest.display()
        ));
    }
    let partial = out.join(format!(".{}.partial", task.id));
    if partial.exists() {
        std::fs::remove_dir_all(&partial).map_err(|e| {
            format!(
                "task `{}`: remove stale {}: {e}",
                task.id,
                partial.display()
            )
        })?;
    }
    let git_deps = discover_git_deps(&task, &prov.sibling_shas)?;
    if !git_deps.is_empty() {
        let dockerfile = render_dockerfile(&task, &prov.sibling_shas, &git_deps).into_bytes();
        if let Some((_, bytes)) = files
            .iter_mut()
            .find(|(rel, _)| rel == Path::new("environment/Dockerfile"))
        {
            *bytes = dockerfile;
        }
    }
    let result = write_task_dir(&task, &partial, &files, prov, &git_deps, git_env);
    if let Err(e) = result {
        let _ = std::fs::remove_dir_all(&partial);
        return Err(e);
    }
    std::fs::rename(&partial, &dest).map_err(|e| {
        let _ = std::fs::remove_dir_all(&partial);
        format!("task `{}`: rename into {}: {e}", task.id, dest.display())
    })?;
    Ok(dest)
}

/// Write the rendered files, `tests/mined_score.py` and the bundles into `dir`.
fn write_task_dir(
    task: &MinedTask,
    dir: &Path,
    files: &[(PathBuf, Vec<u8>)],
    prov: &EmitProvenance,
    git_deps: &[GitDep],
    git_env: &[(String, String)],
) -> Result<(), String> {
    let io = |what: &Path, e: std::io::Error| {
        format!("task `{}`: write {}: {e}", task.id, what.display())
    };
    let mined_score = (
        PathBuf::from("tests/mined_score.py"),
        MINED_SCORE_PY.as_bytes().to_vec(),
    );
    for (rel, bytes) in files.iter().chain(std::iter::once(&mined_score)) {
        let path = dir.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| io(parent, e))?;
        }
        std::fs::write(&path, bytes).map_err(|e| io(&path, e))?;
    }
    let test_sh = dir.join("tests/test.sh");
    set_executable(&test_sh).map_err(|e| io(&test_sh, e))?;

    let (primary, sibling_sources) = source_repos(task)?;
    let env = dir.join("environment");
    create_bundle(
        &primary,
        &task.parent_sha,
        &env.join("repo.bundle"),
        Some(&task.fix_sha),
        &task.id,
    )?;
    if !prov.sibling_shas.is_empty() {
        let sib_dir = env.join("siblings");
        std::fs::create_dir_all(&sib_dir).map_err(|e| io(&sib_dir, e))?;
        for ((repo, sha), src) in prov.sibling_shas.iter().zip(sibling_sources) {
            create_bundle(
                &src,
                sha,
                &sib_dir.join(format!("{repo}.bundle")),
                None,
                &task.id,
            )?;
        }
    }
    if !git_deps.is_empty() {
        let dep_dir = env.join("gitdeps");
        std::fs::create_dir_all(&dep_dir).map_err(|e| io(&dep_dir, e))?;
        for dep in git_deps {
            let dest = dep_dir.join(format!("{}.bundle", dep.name()));
            bundle_git_dep(dep, &dest, git_env, &task.id)?;
        }
    }
    Ok(())
}

#[cfg(unix)]
fn set_executable(path: &Path) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755))
}

#[cfg(not(unix))]
fn set_executable(_path: &Path) -> std::io::Result<()> {
    Ok(())
}

/// The task dirs to emit: `--task` alone, or every immediate subdir with a `task.json`, sorted.
fn discover(args: &EmitArgs) -> Result<Vec<PathBuf>, String> {
    if let Some(id) = &args.task {
        let dir = args.tasks_dir.join(id);
        if !dir.join("task.json").is_file() {
            return Err(format!("task `{id}`: no task.json under {}", dir.display()));
        }
        return Ok(vec![dir]);
    }
    let entries = std::fs::read_dir(&args.tasks_dir)
        .map_err(|e| format!("read --tasks-dir {}: {e}", args.tasks_dir.display()))?;
    let mut dirs: Vec<PathBuf> = entries
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.join("task.json").is_file())
        .collect();
    dirs.sort();
    if dirs.is_empty() {
        return Err(format!("no task dirs under {}", args.tasks_dir.display()));
    }
    Ok(dirs)
}

/// Emit every selected task under `args.out`, plus `<out>/_base`. Returns `(task id, emitted dir)` in sorted id order.
///
/// Order: the git-work-tree guard on `--out`, discovery, `_base`, then the tasks. Stops at the first failing task; tasks already emitted stay complete.
///
/// # Errors
/// `--out` inside a git work tree, no tasks found, or the first task error (prefixed with its task id).
pub fn emit_all(args: &EmitArgs) -> Result<Vec<(String, PathBuf)>, String> {
    let out = absolutize_cwd(&args.out)?;
    guard_out_dir(&out)?;
    let dirs = discover(args)?;
    let base = out.join("_base");
    std::fs::create_dir_all(&base).map_err(|e| format!("create {}: {e}", base.display()))?;
    std::fs::write(base.join("Dockerfile"), HARBOR_BASE_DOCKERFILE)
        .and_then(|()| std::fs::write(base.join("IMAGE"), format!("{HARBOR_BASE_IMAGE}\n")))
        .map_err(|e| format!("write {}: {e}", base.display()))?;
    let emitter_git_sha = git_sha_of(Path::new(env!("CARGO_MANIFEST_DIR")));
    let tasks_dir_git_sha = git_sha_of(&args.tasks_dir);
    let mut emitted = Vec::with_capacity(dirs.len());
    for dir in dirs {
        let name = dir
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        let one = || -> Result<PathBuf, String> {
            let task = load_task(&dir).map_err(|e| e.to_string())?;
            validate_task(&task, &dir)?;
            let prov = EmitProvenance {
                emitter_git_sha: emitter_git_sha.clone(),
                tasks_dir_git_sha: tasks_dir_git_sha.clone(),
                sibling_shas: resolve_sibling_shas(&task)?,
            };
            emit_task(&dir, &out, args.spec_level, &prov)
        };
        let path = one().map_err(|e| format!("task {name}: {e}"))?;
        emitted.push((name, path));
    }
    Ok(emitted)
}

